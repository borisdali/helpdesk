// referencePath is the generated page, relative to this package.
const referencePath = "../docs/PLAYBOOK_REFERENCE.md"

// TestPlaybookReference fails when docs/PLAYBOOK_REFERENCE.md is out of date
// with the embedded system playbooks, or when a playbook breaks a rule the docs
// state. Regenerate the page with `make docs-tools`.
func TestPlaybookReference(t *testing.T) {
	all := loadReferencePlaybooks(t)

	for _, p := range all {
		hasTaxonomy := p.RootCauseClasses != nil
		switch p.PlaybookType {
		case "triage":
			if !hasTaxonomy {
				t.Errorf("%s: a triage playbook must carry root_cause_classes (docs/PLAYBOOKS.md, docs/ATTRIBUTION_CERTS.md)", p.SeriesID)
			}
		case "remediation":
			if hasTaxonomy {
				t.Errorf("%s: a remediation playbook does not carry root_cause_classes", p.SeriesID)
			}
		default:
			t.Errorf("%s: playbook_type %q must be triage or remediation", p.SeriesID, p.PlaybookType)
		}
	}

	toolref.CheckGolden(t, referencePath, renderReference(all))
}

func loadReferencePlaybooks(t *testing.T) []systemPlaybookYAML {
	t.Helper()
	entries, err := FS.ReadDir(".")
	if err != nil {
		t.Fatal(err)
	}
	var out []systemPlaybookYAML
	seen := map[string]string{}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".yaml") {
			continue
		}
		data, err := FS.ReadFile(e.Name())
		if err != nil {
			t.Fatal(err)
		}
		var y systemPlaybookYAML
		if err := yaml.Unmarshal(data, &y); err != nil {
			t.Fatalf("%s: %v", e.Name(), err)
		}
		if y.SeriesID == "" || y.Name == "" {
			t.Fatalf("%s: series_id and name are required", e.Name())
		}
		if prev, dup := seen[y.SeriesID]; dup {
			t.Fatalf("%s and %s share series_id %s", prev, e.Name(), y.SeriesID)
		}
		seen[y.SeriesID] = e.Name()
		out = append(out, y)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].SeriesID < out[j].SeriesID })
	return out
}

func renderReference(all []systemPlaybookYAML) string {
	var triage, remediation []systemPlaybookYAML
	for _, p := range all {
		if p.PlaybookType == "remediation" {
			remediation = append(remediation, p)
		} else {
			triage = append(triage, p)
		}
	}

	var b strings.Builder
	b.WriteString("<!-- Code generated by `make docs-tools`; DO NOT EDIT. -->\n\n")
	b.WriteString("# System playbook reference\n\n")
	fmt.Fprintf(&b, "aiHelpDesk ships %d system playbooks (%d triage, %d remediation). They are embedded in the service "+
		"binaries and seeded into auditd at startup (see [System Playbooks](PLAYBOOKS.md#system-playbooks)). This page "+
		"is generated from the YAML files in `playbooks/`: the version, agent, approval mode and the playbooks each one "+
		"hands off to are read from the files, so it cannot drift from what ships. A *triage* playbook diagnoses and "+
		"ends in a hand-off; a *remediation* playbook acts, under the approval its mode requires. Every triage "+
		"playbook carries a `root_cause_classes` taxonomy (see [ATTRIBUTION_CERTS.md](ATTRIBUTION_CERTS.md)) and no "+
		"remediation playbook does; a test enforces both.\n\n",
		len(all), len(triage), len(remediation))
	b.WriteString("An *entry point* is a playbook an investigation can start from: the triage entry points are matched " +
		"against a query's symptoms by [automatic selection](API.md#automatic-routing-and-playbook-selection). A " +
		"playbook that is not an entry point is reached through a hand-off from another playbook.\n\n")

	writeReferenceTable(&b, "Triage playbooks", triage)
	writeReferenceTable(&b, "Remediation playbooks", remediation)
	return b.String()
}

func writeReferenceTable(b *strings.Builder, title string, pbs []systemPlaybookYAML) {
	fmt.Fprintf(b, "## %s (%d)\n\n", title, len(pbs))
	b.WriteString("| Series ID | Name | Version | Agent | Problem class | Entry point | Approval | Hands off to | What it does |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|\n")
	for _, p := range pbs {
		fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s | %s | %s | %s | %s |\n",
			p.SeriesID, cell(p.Name), p.Version, referenceAgent(p.AgentName), orDash(p.ProblemClass),
			yesNo(p.EntryPoint), orDefault(p.ApprovalMode), handoffs(p), cell(firstSentence(p.Description)))
	}
	b.WriteString("\n")
}

func referenceAgent(name string) string {
	switch name {
	case "postgres_database_agent":
		return "database"
	case "k8s_agent":
		return "k8s"
	case "sysadmin_agent":
		return "sysadmin"
	case "":
		return "—"
	}
	return name
}

func handoffs(p systemPlaybookYAML) string {
	var parts []string
	for _, s := range p.TransitionsTo {
		parts = append(parts, "`"+s+"`")
	}
	for _, s := range p.EscalatesTo {
		parts = append(parts, "`"+s+"` (escalation)")
	}
	if len(parts) == 0 {
		return "—"
	}
	sort.Strings(parts)
	return strings.Join(parts, ", ")
}

func firstSentence(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if i := strings.Index(s, ". "); i >= 0 {
		return s[:i+1]
	}
	return s
}

func cell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

func orDash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}

func orDefault(s string) string {
	if s == "" {
		return "default"
	}
	return s
}

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}
